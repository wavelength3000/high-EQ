     */
    fun matchScenarios(text: String, limit: Int = 3): List<Scenario> {
        if (text.isBlank()) return emptyList()
        val t = text.lowercase()
        return SCENARIOS
            .map { s -> s to s.keywords.count { t.contains(it.lowercase()) } }
            .filter { it.second > 0 }
            .sortedByDescending { it.second }
            .take(limit)
            .map { it.first }
    }

