package com.tools.wereply

/**
 * 内置段子库。生成候选回复时，把对应素材喂给 AI 当「工具箱」。
 *
 * 素材分两类：
 *  - 场景桶（SCENARIOS）：按对方说话的常见语义匹配 —— 对方说「吃饭了吗」就带吃饭的段子，
 *    「我去洗澡了」就带暂离告别的段子。由 matchScenarios 在发请求前本地匹配，
 *    按命中数排序取最贴的前 3 个场景，省 token。匹配只看对方最近两条消息。
 *  - 风格桶（POOLS）：按 Tone.id 分，勾了哪种风格就带哪种素材。
 *
 * 设计原则：
 *  - 素材是工具箱不是稿子：模型只在贴切时借用或化用，不合适就自己写，不许硬套。
 *  - 土味情话和舔狗自嘲只在轻松打趣的场合用，对方认真或生气时禁用（写进 prompt 规则）。
 *  - 全部过得了自家红线：不骂人、不人身攻击、不引导打赏转账（红包/礼物场景只道谢不索要）。
 *
 * 想加段子：场景往 SCENARIOS 里加一行，风格往 POOLS 里加一行，别的地方不用动。
 */
