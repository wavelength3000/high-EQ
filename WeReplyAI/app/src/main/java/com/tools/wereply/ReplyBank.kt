package com.tools.wereply

/**
 * 内置段子库。生成候选回复时，把对应风格的素材喂给 AI 当「工具箱」。
 *
 * 素材来源是全网流传的经典梗：
 *  - 土味情话（"你是什么座？我是为你量身定做"这类）
 *  - 舔狗日记式自嘲（"她回我一个字，我都当论文看"这类）
 *  - 高情商/幽默话术、反讽金句
 *
 * 设计原则：
 *  - 按风格（Tone.id）分桶。只有勾选的风格，它的素材才会进 prompt，省 token。
 *  - 素材是工具箱不是稿子：模型只在贴切时借用或化用，不合适就自己写，不许硬套。
 *  - 土味情话和舔狗自嘲只在轻松打趣的场合用，对方认真或生气时禁用（写进 prompt 规则）。
 *  - 全部过得了自家红线：不骂人、不人身攻击、不引导打赏转账。
 *
 * 想加段子就在对应桶里加一行，别的地方不用动。
 */
object ReplyBank {

    /** 各风格的素材桶。缺桶的风格不带素材。 */
    private val POOLS: Map<String, List<String>> = mapOf(
        Tone.EQ.id to listOf(
            // 经典高情商话术
            "你的心意我收到了，比什么都值钱。",
            "能被你惦记，是今天最开心的一件事。",
            "别急，好事都排着队呢，包括见你。",
            "你说，我听着，一个字都不落。",
            "夸我可以，别停，我记性好。",
            "输给你不丢人，赢了你才麻烦。",
            "先把自己哄开心，再来找我聊，我等你。",
            "来日方长，慢慢说，我不走。",
            "谢谢你愿意跟我说这些，我认真看了。",
            "听你说完，我心情都变好了。",
            // 轻度土味，高情商场合也能用
            "你最近是不是胖了？在我心里的分量越来越重。",
            "你是什么座？我是为你量身定做。"
        ),

        Tone.RATIONAL.id to listOf(
            "就事论事，先把事实对齐，再说对错。",
            "你的感受我理解，但结论下得太早。",
            "情绪先放一放，我们把逻辑捋一遍。",
            "谁对谁错不重要，下一步怎么办才重要。",
            "我尊重你的选择，也请你尊重我的边界。",
            "争输赢没意义，把问题解决掉才算数。"
        ),

        Tone.SHARP.id to listOf(
            // 经典反讽金句，全部不过人身攻击的线
            "你这话跟天气预报似的，听着有道理，天天变。",
            "你的自信要是能分我一半，我早去说脱口秀了。",
            "建议你发言之前，先让脑子排个队。",
            "听君一席话，胜似一席话。",
            "你可真会聊天，把天聊死了还怪天气。",
            "我不跟不讲理的人讲理，怕你听不懂。",
            "就这？我还以为多大的事。",
            "你继续说，我记下来给朋友当笑话讲。"
        ),

        Tone.COLD.id to listOf(
            "嗯，知道了。",
            "还行，先这样。",
            "哦，然后呢。",
            "看心情。",
            "在忙，回头说。",
            "哦。"
        ),

        Tone.PLAYFUL.id to listOf(
            // 俏皮原创风
            "我的高冷是装的，可爱才是原装的。",
            "你再说一遍，我刚才听得太心动。",
            "我这人很简单，夸我就完事了。",
            "别猜了，答案就是有点想你。",
            "刚下播就看见你，今晚运气不错。",
            "警告：跟我聊天容易上头，概不负责。",
            "你这个人眼光怎么那么好，一挑就挑中我。",
            "今天的我：三分乖巧，七分想你。",
            // 经典土味情话
            "你知道我为什么感冒了吗？因为我对你毫无抵抗力。",
            "你知道我的缺点是什么吗？缺点你。",
            "我想买一块地，你的死心塌地。",
            "你累不累？你都在我脑子里跑一天了。",
            "被你赞过的朋友圈，叫甜甜圈。",
            "这是手背，这是脚背，你是我的宝贝。",
            "你会弹吉他吗？不会。那你怎么拨动我心弦的？",
            "你猜我是什么星座？为你量身定做。",
            // 舔狗日记式自嘲
            "她回我一个字，我都当论文看。",
            "她删我好友，一定是怕我看见她朋友圈会吃醋。",
            "她问我借钱，说明需要钱的时候第一个想到的是我。",
            "我给她发了 99 条，她回我：别发了。她一定是心疼我打字累。",
            "她说我人挺好，我哭了，这已经是最高评价。",
            "今天她夸我了，说我不要脸的样子挺可爱的。"
        )
    )

    /** 某个风格对应的素材；没有就是空列表。 */
    fun byTone(toneId: String): List<String> = POOLS[toneId].orEmpty()
}
